import type { Tagged } from "../core/abstractions";

/**
 * Specification map describing each variant of a custom Algebraic Data Type (sum type),
 * where keys are variant `_tag` names and values are payload property records.
 */
export type ADTSpec = Record<string, Record<string, unknown>>;

/**
 * Constructs a single immutable variant type from a tag and payload record.
 *
 * @template Tag The string literal discriminator tag.
 * @template Props The payload properties associated with the variant.
 */
export type ADTVariant<
  Tag extends string,
  Props extends Record<string, unknown> = Record<string, never>,
> = Readonly<Props> & Tagged<Tag>;

/**
 * Constructs the union of all variants defined in an {@link ADTSpec}.
 *
 * @template Spec The ADT specification mapping tags to payload shapes.
 */
export type ADTUnion<Spec extends ADTSpec> = {
  [K in keyof Spec & string]: ADTVariant<K, Spec[K]>;
}[keyof Spec & string];

/**
 * Extracts a specific variant from a tagged union by its `_tag` literal.
 *
 * @template U A union of {@link Tagged} variants.
 * @template Tag The tag literal to extract.
 */
export type ExtractVariant<U extends Tagged, Tag extends U["_tag"]> = Extract<U, { _tag: Tag }>;

/**
 * Exhaustive pattern handler object for a tagged union `U`.
 *
 * @template U A union of {@link Tagged} variants.
 * @template R The return type of the pattern match.
 */
export type ExhaustivePatterns<U extends Tagged, R> = {
  readonly [K in U["_tag"]]: (variant: ExtractVariant<U, K>) => R;
};

/**
 * Partial pattern handler object for a tagged union `U`.
 *
 * @template U A union of {@link Tagged} variants.
 * @template R The return type of matched branches.
 */
export type PartialPatterns<U extends Tagged, R> = {
  readonly [K in U["_tag"]]?: (variant: ExtractVariant<U, K>) => R;
};

/**
 * Constructor function for an individual variant of an {@link ADTSpec}.
 * If the variant requires no properties (`Record<string, never>` or `{}`), the argument is optional.
 *
 * @template Tag The variant tag.
 * @template Props The variant payload properties.
 */
export type VariantConstructor<Tag extends string, Props extends Record<string, unknown>> =
  Record<never, never> extends Props
    ? (props?: Props) => ADTVariant<Tag, Props>
    : (props: Props) => ADTVariant<Tag, Props>;

/**
 * Runtime module generated by {@link defineADT}, providing variant constructors,
 * type guards (`is`), and pattern matching (`match`, `matchPartial`).
 *
 * @template Spec The ADT specification mapping tags to payload shapes.
 */
export type ADTModule<Spec extends ADTSpec> = {
  readonly [K in keyof Spec & string]: VariantConstructor<K, Spec[K]>;
} & {
  /**
   * Type guards for narrowing a union instance to a specific variant.
   */
  readonly is: {
    readonly [K in keyof Spec & string]: (value: ADTUnion<Spec>) => value is ADTVariant<K, Spec[K]>;
  };

  /**
   * Exhaustively matches a variant of `Spec` against handler functions for every tag.
   */
  readonly match: <R>(value: ADTUnion<Spec>, patterns: ExhaustivePatterns<ADTUnion<Spec>, R>) => R;

  /**
   * Partially matches a variant of `Spec`, falling back to `otherwise` for unhandled tags.
   */
  readonly matchPartial: <R, F>(
    value: ADTUnion<Spec>,
    patterns: PartialPatterns<ADTUnion<Spec>, R>,
    otherwise: (unmatched: ADTUnion<Spec>) => F,
  ) => R | F;
};

/**
 * Exhaustively pattern-matches a tagged union value using its `_tag` discriminator.
 *
 * @template U The tagged union type.
 * @template R The result type returned by branch handlers.
 * @param value The tagged union value to inspect.
 * @param patterns Object mapping every `_tag` in `U` to a handler function.
 * @returns The result of invoking the matching branch handler.
 * @example
 * ```ts
 * type Event = { readonly _tag: "click"; readonly x: number } | { readonly _tag: "esc" };
 * const label = matchTagged(event, {
 *   click: (e) => `Clicked at ${e.x}`,
 *   esc: () => "Cancelled",
 * });
 * ```
 */
export function matchTagged<U extends Tagged, R>(value: U, patterns: ExhaustivePatterns<U, R>): R {
  const handler = patterns[value._tag as U["_tag"]];
  return handler(value as ExtractVariant<U, U["_tag"]>);
}

/**
 * Partially pattern-matches a tagged union value, calling `otherwise` when no branch matches.
 *
 * @template U The tagged union type.
 * @template R The result type of matched branches.
 * @template F The result type of the fallback handler.
 * @param value The tagged union value to inspect.
 * @param patterns Partial object mapping selected `_tag`s to handler functions.
 * @param otherwise Fallback function called when `value._tag` is not present in `patterns`.
 * @returns The result of either the matched branch handler or `otherwise(value)`.
 */
export function matchTaggedPartial<U extends Tagged, R, F>(
  value: U,
  patterns: PartialPatterns<U, R>,
  otherwise: (unmatched: U) => F,
): R | F {
  const handler = patterns[value._tag as U["_tag"]];
  return handler ? handler(value as ExtractVariant<U, U["_tag"]>) : otherwise(value);
}

/**
 * Creates a frozen tagged variant object from a tag and optional properties.
 *
 * @template Tag The string literal tag.
 * @template Props The variant payload shape.
 * @param tagName The discriminator tag.
 * @param props Optional properties to merge into the variant.
 * @returns A frozen {@link ADTVariant} object.
 */
export function tag<
  Tag extends string,
  Props extends Record<string, unknown> = Record<string, never>,
>(tagName: Tag, props?: Props): ADTVariant<Tag, Props> {
  return Object.freeze({ ...(props as Props), _tag: tagName });
}

/**
 * Defines a custom Algebraic Data Type (sum type / discriminated union) with zero boilerplate.
 *
 * Uses a lightweight `Proxy` under the hood so arbitrary variant constructors and `.is` type guards
 * require no runtime schema registration while keeping the bundle footprint under 300 bytes.
 *
 * @template Spec Record mapping variant tag names to their payload property types.
 * @returns An {@link ADTModule} with variant constructors, `.is` type guards, `.match`, and `.matchPartial`.
 * @example
 * ```ts
 * type ShapeSpec = {
 *   Circle: { radius: number };
 *   Rectangle: { width: number; height: number };
 *   Point: {};
 * };
 *
 * const Shape = ADT.define<ShapeSpec>();
 * type Shape = ADTUnion<ShapeSpec>;
 *
 * const c = Shape.Circle({ radius: 10 });
 * const area = Shape.match(c, {
 *   Circle: ({ radius }) => Math.PI * radius ** 2,
 *   Rectangle: ({ width, height }) => width * height,
 *   Point: () => 0,
 * });
 * ```
 */
export function defineADT<Spec extends ADTSpec>(): ADTModule<Spec> {
  const isProxy = new Proxy({} as ADTModule<Spec>["is"], {
    get(_target, prop: string) {
      return (value: Tagged) => value._tag === prop;
    },
  });

  return new Proxy(
    {
      is: isProxy,
      match: matchTagged,
      matchPartial: matchTaggedPartial,
    } as unknown as ADTModule<Spec>,
    {
      get(target, prop: string) {
        if (prop in target) {
          return Reflect.get(target, prop);
        }
        return (props?: Record<string, unknown>) => tag(prop, props);
      },
    },
  );
}

/**
 * Namespace of utilities for creating and pattern-matching custom Algebraic Data Types (sum types).
 */
export const ADT = /* @__PURE__ */ Object.freeze({
  define: defineADT,
  tag,
  match: matchTagged,
  matchPartial: matchTaggedPartial,
});
